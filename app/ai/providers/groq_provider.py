import json
from typing import Any
import httpx
import structlog
from app.ai.providers.base import AIProvider
from app.core.config.settings import settings
from app.core.exceptions.base import ExternalAPIError

logger = structlog.get_logger(__name__)

class GroqProvider(AIProvider):
    def __init__(self):
        self.api_key = settings.GROQ_API_KEY
        self.api_url = "https://api.groq.com/openai/v1/chat/completions"
        self.model = "llama-3.3-70b-versatile"

    async def analyze_transcript(self, transcript_text: str) -> dict[str, Any]:
        if not self.api_key:
            raise ExternalAPIError("Groq API key is not configured.", "Groq")

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json"
        }

        system_prompt = (
            "You are an expert AI Quality Assurance Auditor for an automobile service company. "
            "Your task is to analyze the conversation between a car service manager and a customer. "
            "You must evaluate manager compliance, detect any critical violations, and calculate the overall score. "
            "\n"
            "Evaluate according to these checklist parameters:\n"
            "- script_started_correctly: Did manager introduce themselves and open the conversation correctly? (1 for yes, 0 otherwise)\n"
            "- asked_vin: Did they ask for the VIN number of the car? (1 for yes, 0 otherwise)\n"
            "- asked_mileage: Did they ask for mileage? (1 for yes, 0 otherwise)\n"
            "- offered_diagnostics: Did they offer vehicle diagnostics? (1 for yes, 0 otherwise)\n"
            "- asked_repair_history: Did they ask for vehicle history? (1 for yes, 0 otherwise)\n"
            "- service_booking: Did they schedule/book the service? (1 for yes, 0 otherwise)\n"
            "- correct_termination: Did they finish/close the call correctly? (1 for yes, 0 otherwise)\n"
            "- rude: Was the manager impolite, interrupting, or argumentative? (1 for yes, 0 otherwise)\n"
            "- conflict: Was there any argument/conflict from the manager side? (1 for yes, 0 otherwise)\n"
            "- answered_topic: Did the manager answer user questions? (1 for yes, 0 otherwise)\n"
            "- toxic: Was the manager sarcastic, toxic, or dismissive? (1 for yes, 0 otherwise)\n"
            "- violations: Did they violate standard service scripts or guidelines? (1 for yes, 0 otherwise)\n"
            "\n"
            "Set needs_attention to true if the manager was rude, conflicted, toxic, ignored questions, interrupted, or failed basic skills.\n"
            "Calculate manager score dynamically based on the following guidelines:\n"
            "Base score is 0.\n"
            "+1 for introducing themselves (script_started_correctly=1)\n"
            "+1 for asking VIN (asked_vin=1)\n"
            "+1 for asking mileage (asked_mileage=1)\n"
            "+1 for offering diagnostics (offered_diagnostics=1)\n"
            "+2 for booking service (service_booking=1)\n"
            "-2 for failing to answer topic questions (answered_topic=0)\n"
            "-3 for rudeness (rude=1)\n"
            "-5 for conflict (conflict=1)\n"
            "\n"
            "Determine the manager name from the conversation and put it in manager_name. "
            "Determine the type of vehicle work requested by the client in Ukrainian, and put it in work_type. Choose from standard categories like 'ТО', 'Діагностика', 'Ремонт двигуна', 'Ходова', 'Електрика', 'Кузовний ремонт' or 'Інше' (if not clear or not vehicle work). "
            "Write a detailed manager_comment strictly in Ukrainian, explaining the conversation and any issues clearly in Ukrainian. Do NOT use the prefix 'ALERT: ' anywhere in the comment. "
            "Also set issue_type to a short classification (e.g., 'manager_conflict', 'impoliteness', 'script_deviation') or null.\n"
            "NOTE ON WHISPER TRANSCRIPT ERRORS: The transcript is generated by Whisper and may contain phonetic spelling errors or wrong name decodes. "
            "For example, the manager name 'Богдан' might be incorrectly transcribed as 'Балдам', and 'Костя' might be incorrectly transcribed as 'Костян' or 'пацан'. "
            "You MUST use the conversation context to correct these errors. Always output standard, correct names in Ukrainian (e.g., output 'Богдан' instead of 'Балдам', 'Костянтин' or 'Костя' instead of 'Костян') in both `manager_name` and `manager_comment`.\n"

            "\n"
            "Extract these custom metrics:\n"
            "- request_type: Type of request/call, choose from: 'Вхідний дзвінок', 'Запис', 'Авто в роботі', 'Консультація', 'Скарга', or 'Інше'.\n"
            "- branch: Name of the service branch/location if mentioned in the call, otherwise null.\n"
            "- asked_car_body: Did the manager find out or ask for the car body type? (1 for yes, 0 otherwise).\n"
            "- asked_car_year: Did the manager find out or ask for the car year? (1 for yes, 0 otherwise).\n"
            "- service_booking_date: If service is booked (service_booking=1), extract the date and time of the booking (e.g. 'завтра на 13:00', '15.07.2025' or whatever is mentioned), otherwise null.\n"
            "- is_top_100_compliant: Did the manager fully follow all instructions and checklists for the requested work type? Return 'Да' or 'Ні'.\n"
            "- top_100_non_compliant_recommendations: If not fully compliant (is_top_100_compliant='Ні'), detail what standard instructions/recommendations the manager failed to follow, otherwise null.\n"
            "- violations_result: Brief summary of results or major compliance failures (e.g. 'Не уточнив правильних установок для реногранта з 3-й'), otherwise null.\n"
            "- spare_parts: Details of any spare parts discussed, ordered, or photographed during the call, otherwise null.\n"
            "\n"
            "You MUST output a strict JSON object containing these keys exactly, and NO other conversational text or markdown blocks."
        )

        user_content = f"Transcript:\n{transcript_text}"

        models_to_try = [
            "llama-3.3-70b-versatile",
            "llama-3.1-8b-instant",
            "mixtral-8x7b-32768"
        ]

        last_error = None
        for model in models_to_try:
            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_content}
                ],
                "response_format": {"type": "json_object"},
                "temperature": 0.1
            }

            logger.info("Attempting AI analysis with Groq model", model=model)
            async with httpx.AsyncClient(timeout=60.0) as client:
                try:
                    response = await client.post(self.api_url, headers=headers, json=payload)
                    response.raise_for_status()
                    data = response.json()
                    content = data["choices"][0]["message"]["content"]
                    return json.loads(content)
                except httpx.HTTPStatusError as e:
                    logger.error("Groq API request failed for model", model=model, status_code=e.response.status_code, error=e.response.text)
                    last_error = e
                    if e.response.status_code == 429:
                        logger.warning("Rate limit exceeded for model, attempting fallback", model=model)
                        continue
                    raise ExternalAPIError(f"HTTP error {e.response.status_code}: {e.response.text}", "Groq")
                except Exception as e:
                    logger.error("Unexpected error in Groq provider for model", model=model, error=str(e))
                    last_error = e
                    continue

        raise ExternalAPIError(f"All Groq models failed. Last error: {str(last_error)}", "Groq")
